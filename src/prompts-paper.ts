export interface ResearchHandle {
    handle: string; // "R3"
    kind: string;
    citation: string;
    summary: string;
    quote?: string;
    url?: string;
}

export function researchBlock(items: ResearchHandle[], max = 24, quoteChars = 320): string {
    if (!items.length) return '## 조사 자료\n(없음 — 조사에서 아무것도 얻지 못했다. 자료 없이 쓰되, 확신 없는 판례·문헌은 인용하지 않는다)';
    return [
        '## 조사 자료 (출처가 있다. 인용하려면 핸들을 ⟦R3⟧ 처럼 쓴다)',
        ...items.slice(0, max).map((f) => {
            const q = (f.quote ?? f.summary).replace(/\s+/g, ' ').slice(0, quoteChars);
            if (f.kind === 'case') {
                // 판례·결정은 핸들이 아니라 정식 인용으로 쓴다 — 그래야 검증기가 사건번호로 원문을 대조한다.
                return `- [${f.handle}] (판례·결정) **인용할 때는 ⟦${f.citation}⟧ 라고 그대로 쓴다** (핸들 ${f.handle} 로 쓰지 않는다)${f.url ? ` <${f.url}>` : ''}\n  "${q}"`;
            }
            if (f.kind === 'doctrine') {
                // 문헌(KCI·서지)은 **초록·서지까지만** 확보된 것이다. 정식 서지로 인용해야 원문 사다리가 돌고,
                // 전문을 못 구하면 필자에게 묻는다. 핸들로 쓰면 "공개자료"로 조용히 통과한다(실제로 그랬다).
                return `- [${f.handle}] (문헌 — 서지·초록만 확보, 전문 아님) **인용할 때는 ⟦${f.citation}⟧ 라고 정식 서지로 쓴다** (핸들 ${f.handle} 로 쓰지 않는다). 초록에 없는 내용을 이 문헌이 말한다고 단정하지 않는다${f.url ? ` <${f.url}>` : ''}\n  "${q}"`;
            }
            return `- [${f.handle}] (${f.kind}) ${f.citation.slice(0, 140)}${f.url ? ` <${f.url}>` : ''}\n  "${q}"`;
        }),
    ].join('\n');
}

export function thesisBlock(t: {
    title: string;
    thesis: string;
    concepts: { term: string; definition: string }[];
    questions: string[];
    position: string;
    scope: string;
    method: string;
}): string {
    return [
        '## 논문 설계',
        `제목: ${t.title}`,
        `중심 논지: ${t.thesis}`,
        '핵심 개념:',
        ...t.concepts.map((c) => `- **${c.term}** — ${c.definition}`),
        '연구질문:',
        ...t.questions.map((q, i) => `${i + 1}. ${q}`),
        `입장: ${t.position}`,
        `범위: ${t.scope}`,
        `방법: ${t.method}`,
    ].join('\n');
}

export function outlineBlock(sections: { number: string; title: string; role: string; brief: string }[]): string {
    return ['## 목차', ...sections.map((s) => `${s.number}. ${s.title} [${s.role}] — ${s.brief}`)].join('\n');
}

/** 앞 장들의 요지 — 집필 모델이 반복하지 않도록. 첫 문단 + 소절 제목만 준다. */
export function previousBlock(sections: { number: string; title: string; draft?: string }[]): string {
    const done = sections.filter((s) => s.draft);
    if (!done.length) return '';
    return [
        '## 앞 장의 요지 (이미 쓴 것. 반복하지 말고 "앞서 본 바와 같이"로 받는다)',
        ...done.map((s) => {
            const text = s.draft ?? '';
            const heads = [...text.matchAll(/^###\s+(.+)$/gm)].map((m) => m[1]!.trim());
            const first = text.split(/\n\s*\n/).find((p) => p.trim() && !p.trim().startsWith('#')) ?? '';
            return `### ${s.number}. ${s.title}\n${first.replace(/\s+/g, ' ').slice(0, 500)}${heads.length ? `\n소절: ${heads.join(' / ')}` : ''}`;
        }),
    ].join('\n');
}

