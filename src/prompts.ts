/** 반대측에 주는 자료 — 찬성측의 논증은 일부러 뺀다. */
export function conInput(claim: { proposition: string; authority: { citation: string; type: string }[] }, sources: string): string {
    return [
        '## 공격 대상 명제',
        claim.proposition,
        '',
        '## 이 명제가 인용한 권위',
        ...claim.authority.map((a, i) => `${i + 1}. [${a.type}] ${a.citation}`),
        '',
        '## 권위 원문 발췌 (도구가 원문에서 직접 뽑은 것)',
        sources || '(원문을 확보하지 못했다 — 확보되지 않은 권위를 근거로 삼지 말 것)',
        '',
        '반대 논증 하나를 만든다.',
    ].join('\n');
}

export function judgeInput(
    claim: { proposition: string; premise: string; step: string; authority: { citation: string }[] },
    objection: { objection: string; alternative: string; attack: string; defeat: string; strength?: string },
    sources: string,
    /** 사람이 확인해 준 사실 — 있으면 판정 입력에 붙는다. 없으면 미결이 미결로 남는다. */
    humanFacts?: string,
): string {
    return [
        '## 명제',
        claim.proposition,
        '',
        '## 찬성측이 밝힌 전제',
        claim.premise,
        '',
        '## 찬성측의 도약',
        claim.step,
        '',
        '## 인용된 권위',
        ...claim.authority.map((a) => `- ${a.citation}`),
        '',
        '## 반대 논증',
        objection.objection,
        '',
        '## 반대가 제시한 대안',
        objection.alternative,
        '',
        `## 공격 유형: ${objection.attack}`,
        // 반대측이 스스로 매긴 무게. JUDGE_PROMPT_PAPER 의 "strength 가 none·minor 면 …" 규칙은 이 줄이 없으면 걸릴 수 없다.
        ...(objection.strength ? ['', `## 반대의 무게(strength): ${objection.strength}`] : []),
        '',
        '## 반대측이 밝힌, 자신을 죽일 조건',
        objection.defeat,
        '',
        '## 권위 원문 발췌',
        sources || '(원문 미확보)',
        ...(humanFacts ? ['', '## 사람이 확인해 준 사실 (기록에 없던 것)', humanFacts] : []),
        '',
        humanFacts
            ? '사람이 확인해 준 사실을 반영하여 다시 판정한다. 그 사실로 미결이 풀리면 풀린 것이고, 여전히 부족하면 미결로 남긴다.'
            : '판정한다.',
    ].join('\n');
}


