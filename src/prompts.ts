/** 워커 입력: 의도 + 후보 조문 원문. */
export function workerInput(
    intent: { question: string; kind: string; needs: string },
    candidates: { law: string; articleNo: string; heading: string; excerpt: string }[],
    /** 전문을 확보한 학설 — 있으면 우선 인용한다. */
    literature: { citation: string; title: string; excerpt: string; hasFullText: boolean }[] = [],
    /** 코퍼스에서 검색·리랭크된 판례. 기억에서 꺼내는 대신 이것을 인용한다. */
    cases: { citation: string; name: string; summary: string }[] = [],
    /** 조사로 확인된 사실 — 보도·공개자료. 사실관계의 근거다. */
    facts: { citation: string; quote: string; url?: string }[] = [],
): string {
    return [
        '## 논증 의도',
        `질문: ${intent.question}`,
        `종류: ${intent.kind}`,
        `필요한 권위: ${intent.needs}`,
        '',
        '## 후보 조문의 실제 원문 (코퍼스에서 직접 읽은 것)',
        candidates.length
            ? candidates.map((c) => `### ${c.law} ${c.articleNo} (${c.heading})\n${c.excerpt}`).join('\n\n')
            : '(관련 조문을 찾지 못했다 — 인용 없이 명제를 만들지 말고, 원문이 없다는 사실을 전제에 적는다)',
        '',
        '',
        '## 조사로 확인된 사실 (출처가 있다. 사실관계를 이 위에 세운다)',
        facts.length
            ? facts.map((f) => `- ${f.citation}\n  "${f.quote.slice(0, 300)}"`).join('\n')
            : '(없음. 사실관계를 단정하지 말고, 확인되지 않은 것은 확인되지 않았다고 쓴다)',
        '',
        '## 검색된 판례 (코퍼스에 실재한다. 인용하면 검증에서 전문을 읽는다)',
        cases.length
            ? cases.map((c) => `- ${c.citation} — ${c.name}\n  판시사항: ${c.summary.slice(0, 260)}`).join('\n')
            : '(이 쟁점에서 검색된 판례 없음. 판례를 지어내지 말고 조문·학설로 논증한다)',
        '',
        '## 확보된 학설 (원문 있음 — 인용하면 검증에서 전문을 읽는다)',
        literature.length
            ? literature.map((l) => `- ${l.citation}${l.hasFullText ? '' : ' (전문 미확보)'}\n  발췌: ${l.excerpt.slice(0, 400)}`).join('\n')
            : '(없음. 학설을 인용하려면 직접 인용해도 되지만, 검증에서 원문이 없으면 그 명제는 근거 부족이 된다)',
        '',
        '이 원문과 학설로 명제 하나를 만든다.',
    ].join('\n');
}

export function plannerInput(
    issue: { question: string; why_contested: string; positions: string[] },
    /** 코퍼스에서 실제로 찾은 판례. 지어낸 사건번호 대신 이것을 쓴다. */
    cases: { citation: string; name: string; summary: string }[] = [],
): string {
    return [
        `## 쟁점\n${issue.question}`,
        '',
        `## 이 쟁점이 다투어지는 이유\n${issue.why_contested}`,
        '',
        `## 현재 존재하는 견해들\n${issue.positions.join(' / ')}`,
        ...(cases.length
            ? [
                  '',
                  '## 코퍼스에서 검색된 판례 (실재하는 사건이다. 인용하려면 이 형태 그대로 쓴다)',
                  ...cases.map((c) => `- ${c.citation} — ${c.name} :: ${c.summary.slice(0, 200)}`),
              ]
            : []),
        '',
        '확립해야 할 것들을 논증 의도로 나눈다.',
    ].join('\n');
}
